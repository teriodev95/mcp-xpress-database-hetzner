    INDEX idx_raw_solicitud_id (id),
    INDEX idx_raw_agencia (agencia),
    INDEX idx_raw_semana_anio (anio, semana)
) ENGINE=InnoDB DEFAULT CHARSET=utf8 COMMENT='Copia raw de solicitudes tal cual llegan al INSERT';


