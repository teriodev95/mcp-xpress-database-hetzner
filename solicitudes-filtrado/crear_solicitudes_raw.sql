    documentos                      LONGTEXT DEFAULT NULL,
    gps_lat                         DECIMAL(10,6) DEFAULT NULL,
    gps_lng                         DECIMAL(10,6) DEFAULT NULL,
    gps_timestamp                   VARCHAR(32) DEFAULT NULL,
